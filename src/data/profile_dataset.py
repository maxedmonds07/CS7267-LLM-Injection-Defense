"""Profile the unified dataset: shape, nulls, class balance, text length and duplicates.

Writes a JSON metric (tracked by DVC, so `dvc metrics diff` shows changes) and a Markdown
report for the data card. A null is "expected" only in the attack fields of a benign row;
any other null, or blank text, is reported as unexpected.

Usage: python src/data/profile_dataset.py [--data PATH] [--out PATH] [--report PATH]
"""

import argparse
import json
from pathlib import Path

import pandas as pd

ATTACK_FIELDS = ("attack_kind", "attack_objective", "attack_family")


def _balance(labels: pd.Series) -> dict:
    adversarial = int(labels.sum())
    return {
        "adversarial": adversarial,
        "benign": int(len(labels) - adversarial),
        "adversarial_share": round(adversarial / len(labels), 3),
    }


def profile(df: pd.DataFrame) -> dict:
    missing = df.isna()
    missing["text"] |= df["text"].fillna("").str.strip().eq("")
    adversarial = df["label"].eq(1)

    nulls = {
        column: {
            "total": int(missing[column].sum()),
            "benign": int(missing.loc[~adversarial, column].sum()),
            "adversarial": int(missing.loc[adversarial, column].sum()),
        }
        for column in df.columns
    }
    unexpected = {
        column: counts["adversarial"] if column in ATTACK_FIELDS else counts["total"]
        for column, counts in nulls.items()
    }

    lengths = df["text"].fillna("").str.len()
    text_length = {
        source: {
            ("adversarial" if label else "benign"): {
                "min": int(part.min()),
                "median": float(part.median()),
                "max": int(part.max()),
            }
            for label, part in by_source.groupby(df["label"])
        }
        for source, by_source in lengths.groupby(df["source"])
    }

    return {
        "shape": {"rows": len(df), "columns": len(df.columns)},
        "nulls": nulls,
        "unexpected_nulls": {column: count for column, count in unexpected.items() if count},
        "class_balance": {
            "overall": _balance(df["label"]),
            **{
                f"by_{key}": {value: _balance(part) for value, part in df["label"].groupby(df[key])}
                for key in ("source", "attack_surface", "role", "split")
            },
        },
        "text_length": text_length,
        "duplicates": {
            "ids": int(df["id"].duplicated().sum()),
            "texts": int(df["text"].duplicated().sum()),
        },
    }


def _table(header, rows) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    return "\n".join(lines + ["| " + " | ".join(str(c) for c in row) + " |" for row in rows])


def to_markdown(result: dict) -> str:
    shape = result["shape"]
    unexpected = result["unexpected_nulls"]
    sections = [
        "# Dataset profile",
        "Generated by `src/data/profile_dataset.py` from `data/processed/dataset.parquet`; "
        "do not edit by hand.",
        f"## Shape\n\n{shape['rows']:,} rows × {shape['columns']} columns.",
        "## Nulls\n\nBlank text counts as null. Attack fields are null by design on benign rows.\n\n"
        + _table(
            ["Column", "Nulls", "On benign rows", "On adversarial rows"],
            [[c, f"{n['total']:,}", f"{n['benign']:,}", f"{n['adversarial']:,}"] for c, n in result["nulls"].items()],
        )
        + "\n\nUnexpected nulls: "
        + (", ".join(f"{c} ({n})" for c, n in unexpected.items()) if unexpected else "none")
        + ".",
    ]
    for key, title in [
        ("overall", "overall"),
        ("by_source", "by source"),
        ("by_attack_surface", "by attack surface"),
        ("by_role", "by role"),
        ("by_split", "by split"),
    ]:
        balance = result["class_balance"][key]
        groups = {"all rows": balance} if key == "overall" else balance
        sections.append(
            f"## Class balance, {title}\n\n"
            + _table(
                ["Group", "Adversarial", "Benign", "Adversarial share"],
                [[g, f"{b['adversarial']:,}", f"{b['benign']:,}", f"{b['adversarial_share']:.1%}"]
                 for g, b in groups.items()],
            )
        )
    sections.append(
        "## Text length (characters)\n\n"
        + _table(
            ["Source", "Label", "Min", "Median", "Max"],
            [[source, label, f"{s['min']:,}", f"{s['median']:,.0f}", f"{s['max']:,}"]
             for source, labels in result["text_length"].items()
             for label, s in sorted(labels.items(), reverse=True)],
        )
    )
    duplicates = result["duplicates"]
    sections.append(
        f"## Duplicates\n\nDuplicate ids: {duplicates['ids']}. Duplicate texts: {duplicates['texts']}."
    )
    return "\n\n".join(sections) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--data", default="data/processed/dataset.parquet", type=Path)
    parser.add_argument("--out", default="data/processed/profile.json", type=Path)
    parser.add_argument("--report", default="data/processed/profile.md", type=Path)
    args = parser.parse_args()

    result = profile(pd.read_parquet(args.data))
    args.out.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    args.report.write_text(to_markdown(result))
    print(f"{result['shape']['rows']} rows profiled -> {args.out}, {args.report}")


if __name__ == "__main__":
    main()
